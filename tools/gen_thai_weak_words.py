#!/usr/bin/env python3
"""Generate cr3gui/data/wordbreak/th_weak_words.txt

"Weak" Thai words are short dictionary words that are rare as words, and
that are mostly met as syllables of names and transliterated foreign words
(นิ, ริ, จู, ฮี, เฮ, ไอ: จูนิเปอร์, ไอริส, เฮร่า...). ThaiWordBreak still uses
them to segment text, but never allows a line break on either side of them.

Selection: words of the word list with at most MAX_LEN code points, and
a frequency below MIN_FREQ in the Thai National Corpus word frequency
list from PyThaiNLP (tnc_freq.txt, CC0-1.0):
  https://github.com/PyThaiNLP/pythainlp/blob/dev/pythainlp/corpus/tnc_freq.txt

With 2 code points, frequency separates these syllables from real words
well (all names syllables checked were < 4700, all common short words
> 5200). With 3 or more, both ranges overlap a lot, so we don't go there:
names like ยูโดร่า (ยูโด|ร่า) still need to be added as user words.

Usage:
  gen_thai_weak_words.py th_words.txt tnc_freq.txt > th_weak_words.txt
"""

import sys

MAX_LEN = 2
MIN_FREQ = 5000


def is_thai(c):
    return 0x0E01 <= ord(c) <= 0x0E3A or 0x0E40 <= ord(c) <= 0x0E4E


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    words_file, freq_file = sys.argv[1], sys.argv[2]
    freq = {}
    with open(freq_file, encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 2 and parts[1].isdigit():
                freq[parts[0]] = freq.get(parts[0], 0) + int(parts[1])
    weak = set()
    with open(words_file, encoding="utf-8") as f:
        for line in f:
            w = line.strip()
            if w and len(w) <= MAX_LEN and all(is_thai(c) for c in w) and freq.get(w, 0) < MIN_FREQ:
                weak.add(w)
    out = sys.stdout
    out.reconfigure(encoding="utf-8", newline="\n")
    out.write("# Generated by crengine/tools/gen_thai_weak_words.py: do not edit\n")
    out.write(f"# Words of th_words.txt with <= {MAX_LEN} chars and a frequency < {MIN_FREQ}\n")
    out.write("# in PyThaiNLP tnc_freq.txt (Thai National Corpus, CC0-1.0)\n")
    for w in sorted(weak):
        out.write(w + "\n")


if __name__ == "__main__":
    main()
